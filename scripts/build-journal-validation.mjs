// Vercel compiles this project's API entrypoints as CommonJS. Generate the
// server validators from the browser's dependency-free domain modules so both
// enforce the same contract without requiring .mjs files from a CJS function.
import { readFile, writeFile } from 'node:fs/promises';
const source = async name => (await readFile(new URL(`../architecture-v2/src/domain/${name}.mjs`, import.meta.url),'utf8'))
  .replace(/\r\n/g,'\n').replace(/^import .*;\n/gm,'').replace(/^export (const|function) /gm,'$1 ');
const output = '// Generated by scripts/build-journal-validation.mjs. Do not edit directly.\n'
  + await source('cocktails') + '\n' + await source('restaurant-awards')
  + '\n' + await source('hidden-places') + '\nmodule.exports = { validCocktailCollections, validAward, validHiddenPlaces };\n';
const target = new URL('../api/_lib/journal-validation.cjs',import.meta.url);
if(process.argv.includes('--check')) {
  if((await readFile(target,'utf8')).replace(/\r\n/g,'\n') !== output) throw new Error('Regenerate journal-validation.cjs before deploying.');
} else await writeFile(target,output);
